//! The `TaskBackend` trait and the mapping from agent-run job states to A2A
//! task states.

use std::collections::HashMap;

use a2a::{Artifact, Task, TaskState, TaskStatus};

use crate::core::job::JobStatus;

/// A task in the A2A protocol, as the wrapped backend reports it.
///
/// The backend (implemented by the later slices for sessions or jobs) maps
/// its own task records onto this minimal view; the bindings serialize it
/// into the A2A wire `Task` with camelCase fields.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct A2aTask {
    /// A2A task id (job id / session turn id).
    pub id: String,
    /// Context id (conversation/session name) this task belongs to.
    pub context_id: Option<String>,
    /// Current A2A state.
    pub state: TaskState,
    /// Optional human/tool status message (e.g. a result summary).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub status_message: Option<String>,
    /// Optional error string for failed/rejected tasks.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error: Option<String>,
    /// Optional artifacts generated by the task (e.g. result text, diff).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub artifacts: Option<Vec<Artifact>>,
}

impl From<A2aTask> for Task {
    fn from(t: A2aTask) -> Self {
        let mut metadata = HashMap::new();
        if let Some(msg) = t.status_message.clone() {
            metadata.insert("statusMessage".to_string(), serde_json::json!(msg));
        }
        if let Some(err) = t.error.clone() {
            metadata.insert("error".to_string(), serde_json::json!(err));
        }
        let status = TaskStatus {
            state: t.state,
            message: None,
            timestamp: None,
        };
        Task {
            id: t.id.clone(),
            context_id: t.context_id.unwrap_or_default(),
            status,
            artifacts: t.artifacts,
            history: None,
            metadata: Some(metadata),
        }
    }
}

impl From<&Task> for A2aTask {
    fn from(t: &Task) -> Self {
        A2aTask {
            id: t.id.clone(),
            context_id: Some(t.context_id.clone()),
            state: t.status.state.clone(),
            status_message: t
                .status
                .message
                .as_ref()
                .and_then(|m| m.text().map(|s| s.to_string())),
            error: None,
            artifacts: t.artifacts.clone(),
        }
    }
}

/// The A2A error type used by backends and bindings. The `code` is a stable
/// identifier serialized into the crate's `{"error", "code"}` JSON error
/// shape; the field names follow the A2A error codes where the protocol
/// defines one (e.g. `taskNotFound`, `unsupported`).
#[derive(Debug, Clone, thiserror::Error)]
#[error("{message}")]
pub struct A2AError {
    pub code: &'static str,
    pub message: String,
}

impl A2AError {
    /// Unknown task (A2A error code for `TaskNotFound`, HTTP 404).
    pub fn task_not_found(task_id: &str) -> Self {
        A2AError {
            code: "taskNotFound",
            message: format!("task not found: {task_id}"),
        }
    }

    /// The task cannot be canceled from its current state (A2A
    /// `TaskNotCancelable`).
    pub fn task_not_cancelable(task_id: &str) -> Self {
        A2AError {
            code: "taskNotCancelable",
            message: format!("task not cancelable: {task_id}"),
        }
    }

    /// A method this slice deliberately does not implement (A2A
    /// `unsupportedOperation`). The bindings answer HTTP 501 for these,
    /// never 404.
    pub fn unsupported(what: &str) -> Self {
        A2AError {
            code: "unsupported",
            message: format!("{what} is not supported by this agent"),
        }
    }

    /// Invalid request parameters.
    pub fn invalid_params(message: impl Into<String>) -> Self {
        A2AError {
            code: "invalidParams",
            message: message.into(),
        }
    }

    /// Internal failure.
    pub fn internal(message: impl Into<String>) -> Self {
        A2AError {
            code: "internal",
            message: message.into(),
        }
    }
}

/// Backend contract for the A2A task read/cancel surface.
///
/// Implemented in later slices by `agent-orchestrate` (sessions) and
/// `agent-run-api` (jobs); this slice only wires it and tests it against an
/// in-memory fake.
pub trait TaskBackend: Send + Sync {
    /// Returns the task with the given id, or an [`A2AError::task_not_found`]
    /// error (`code: "taskNotFound"`, HTTP 404) when it does not exist.
    fn get_task(&self, task_id: &str) -> Result<A2aTask, A2AError>;

    /// Lists tasks, optionally filtered by context id and/or state.
    fn list_tasks(
        &self,
        context_id: Option<&str>,
        state: Option<&TaskState>,
    ) -> Result<Vec<A2aTask>, A2AError>;

    /// Requests cancellation of the given task. The backend decides whether
    /// the task is in a cancelable state; otherwise it must return an
    /// [`A2AError::task_not_cancelable`] error.
    fn cancel_task(&self, task_id: &str) -> Result<A2aTask, A2AError>;
}

/// Maps an agent-run [`JobStatus`] to the A2A [`TaskState`].
///
/// The mapping is deliberate rather than lossy:
///
/// - `Running` -> [`TaskState::Working`] (the agent is actively working)
/// - `Done` -> [`TaskState::Completed`]
/// - `Failed`, `Incomplete` (agy exited cleanly with no usable result) and
///   `QuotaExhausted` (upstream model quota) -> [`TaskState::Failed`]
/// - `SelfTerminated` (137/143, killed by a signal) and `Killed`
///   (explicitly killed) -> [`TaskState::Canceled`] (the run stopped before
///   reaching an outcome; A2A reserves `failed` for a genuine error outcome,
///   so a halted run maps to `canceled`)
pub fn map_job_status(status: JobStatus) -> TaskState {
    match status {
        JobStatus::Running => TaskState::Working,
        JobStatus::Done => TaskState::Completed,
        JobStatus::Failed => TaskState::Failed,
        JobStatus::Incomplete => TaskState::Failed,
        JobStatus::QuotaExhausted => TaskState::Failed,
        JobStatus::SelfTerminated => TaskState::Canceled,
        JobStatus::Killed => TaskState::Canceled,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn job_status_mapping_table() {
        let cases = [
            (JobStatus::Running, TaskState::Working),
            (JobStatus::Done, TaskState::Completed),
            (JobStatus::Failed, TaskState::Failed),
            (JobStatus::Incomplete, TaskState::Failed),
            (JobStatus::QuotaExhausted, TaskState::Failed),
            (JobStatus::SelfTerminated, TaskState::Canceled),
            (JobStatus::Killed, TaskState::Canceled),
        ];
        for (job, expected) in cases {
            assert_eq!(map_job_status(job), expected, "mapping {job:?}");
        }
    }

    #[test]
    fn a2a_task_converts_onto_wire_task() {
        let t = A2aTask {
            id: "job-1".to_string(),
            context_id: Some("conv-1".to_string()),
            state: TaskState::Completed,
            status_message: Some("done".to_string()),
            error: None,
            artifacts: None,
        };
        let wire: Task = t.clone().into();
        assert_eq!(wire.id, "job-1");
        assert_eq!(wire.context_id, "conv-1");
        assert_eq!(wire.status.state, TaskState::Completed);
        let back: A2aTask = (&wire).into();
        assert_eq!(back.id, t.id);
        assert_eq!(back.state, t.state);
    }
}
